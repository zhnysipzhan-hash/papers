# ---------------- helpers ----------------
def scrub(el):
    """Remove ids/bookmarks/render hints from a cloned element."""
    for x in el.iter():
        for a in list(x.attrib):
            if a.startswith('{%s}' % W14) or a.startswith('{%s}rsid' % W):
                del x.attrib[a]
    for tag in ('bookmarkStart', 'bookmarkEnd', 'lastRenderedPageBreak', 'proofErr'):
        for x in el.findall('.//' + q(tag)):
            x.getparent().remove(x)
    return el

def ppr_of(tmpl):
    p = tmpl.find(q('pPr'))
    return scrub(copy.deepcopy(p)) if p is not None else None

def new_p(tmpl):
    p = etree.Element(q('p'))
    pp = ppr_of(tmpl)
    if pp is not None:
        p.append(pp)
    return p

def mk_run(text, bold=None, sub=False, sup=False, hl=False):
    r = etree.Element(q('r'))
    rpr = etree.SubElement(r, q('rPr'))
    if bold is True:
        etree.SubElement(rpr, q('b')); etree.SubElement(rpr, q('bCs'))
    elif bold is False:
        etree.SubElement(rpr, q('b'), {q('val'): '0'}); etree.SubElement(rpr, q('bCs'), {q('val'): '0'})
    if hl:
        etree.SubElement(rpr, q('highlight'), {q('val'): 'yellow'})
    if sub or sup:
        etree.SubElement(rpr, q('vertAlign'), {q('val'): 'subscript' if sub else 'superscript'})
    if len(rpr) == 0:
        r.remove(rpr)
    t = etree.SubElement(r, q('t')); t.text = text
    t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    return r

TOK = re.compile(r'(\*\*.+?\*\*|~[^~]+~|\^[^^]+\^|\[\[HL:.+?\]\])')
def add_text(p, text, bold=None):
    for part in TOK.split(text):
        if not part:
            continue
        if part.startswith('**'):
            p.append(mk_run(part[2:-2], bold=True))
        elif part.startswith('~'):
            p.append(mk_run(part[1:-1], bold=bold, sub=True))
        elif part.startswith('^'):
            p.append(mk_run(part[1:-1], bold=bold, sup=True))
        elif part.startswith('[[HL:'):
            p.append(mk_run(part[5:-2], bold=bold, hl=True))
        else:
            p.append(mk_run(part, bold=bold))
    return p

