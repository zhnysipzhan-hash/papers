def para(text, ind0=False):
    p = new_p(T_PARA)
    if ind0:
        ppr = p.find(q('pPr'))
        ind = etree.Element(q('ind'), {q('firstLine'): '0'})
        ppr.insert(0, ind)
    emit(add_text(p, text))

def runin(label, text, tmpl=T_RUNIN):
    p = new_p(tmpl)
    p.append(mk_run(label, bold=True)); p.append(mk_run(' '))
    emit(add_text(p, text))

def heading_runin(tmpl, label, text):
    p = new_p(tmpl)
    p.append(mk_run(label)); p.append(mk_run(' '))
    emit(add_text(p, text, bold=False))

