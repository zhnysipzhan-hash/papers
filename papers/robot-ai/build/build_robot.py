def table_from_mine(idx):
    t = scrub(copy.deepcopy(M[idx]))
    for b in t.iter():
        if b.get(q('color')) == 'D9D9D9':
            b.set(q('color'), '000000')
        if b.tag == q('shd') and b.get(q('fill')) == 'EDEDED':
            b.set(q('fill'), 'FFFFFF')
        if b.tag == q('spacing'):
            for a in (q('line'), q('lineRule')):
                b.attrib.pop(a, None)
    emit(t)

def table_from_rows(tmpl_tbl, rows):
    t = scrub(copy.deepcopy(tmpl_tbl))
    trs = t.findall(q('tr'))
    for tr, row in zip(trs, rows):
        for tc, text in zip(tr.findall(q('tc')), row):
            ps = tc.findall(q('p'))
            p0 = ps[0]
            for extra in ps[1:]:
                tc.remove(extra)
            bold = p0.find('.//' + q('b')) is not None
            for r in p0.findall(q('r')):
                p0.remove(r)
            add_text(p0, text, bold=True if bold else None)
    emit(t)

