RID_MAP = {'rId9': 'rId10', 'rId10': 'rId11'}  # mine figure rels -> example figure rels
def figure_from_mine(idx, cap):
    src = scrub(copy.deepcopy(M[idx]))
    p = new_p(T_FIG)
    for r in src.findall(q('r')):
        p.append(r)
    for b in p.iter('{http://schemas.openxmlformats.org/drawingml/2006/main}blip'):
        b.set('{%s}embed' % R, RID_MAP[b.get('{%s}embed' % R)])
    emit(p)
    emit(add_text(new_p(T_FIGCAP), cap))

def math_from_mine(idx):
    emit(scrub(copy.deepcopy(M[idx])))

def copy_mine(idx, repl=(), ind0=False, tmpl=None):
    """Copy the author's paragraph runs (keeps sub/superscripts) into example formatting."""
    src = scrub(copy.deepcopy(M[idx]))
    p = new_p(tmpl if tmpl is not None else T_PARA)
    if ind0:
        p.find(q('pPr')).insert(0, etree.Element(q('ind'), {q('firstLine'): '0'}))
    for r in src.findall(q('r')):
        p.append(r)
    for a, b in repl:
        done = False
        for t in p.iter(q('t')):
            if t.text and a in t.text:
                t.text = t.text.replace(a, b); done = True
        assert done, ('replace failed', idx, a)
    emit(p)

def mine_list_text(idx):
    src = M[idx]
    return ''.join(t.text or '' for t in src.iter(q('t')))

